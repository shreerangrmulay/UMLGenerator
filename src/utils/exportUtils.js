import { toPng } from 'html-to-image';
import JSZip from 'jszip';

/**
 * Triggers a browser download of a Blob or text content
 */
export function downloadFile(content, fileName, mimeType = 'text/plain;charset=utf-8') {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Exports diagram as JSON file
 */
export function exportDiagramAsJSON(classes, relationships, diagramName = 'uml-diagram') {
  const data = {
    generator: 'UML Class Diagram Generator',
    version: '1.0.0',
    exportedAt: new Date().toISOString(),
    diagramName,
    classes,
    relationships
  };

  const jsonString = JSON.stringify(data, null, 2);
  downloadFile(jsonString, `${diagramName.toLowerCase().replace(/\s+/g, '-')}.json`, 'application/json');
}

/**
 * Exports the React Flow canvas as a PNG image
 */
export async function exportCanvasAsPNG(containerElement, fileName = 'uml-diagram.png') {
  if (!containerElement) {
    throw new Error('Canvas element not found for export.');
  }

  // Find the viewport element inside React Flow
  const viewport = containerElement.querySelector('.react-flow__viewport') || containerElement;

  try {
    const dataUrl = await toPng(viewport, {
      backgroundColor: '#ffffff',
      quality: 1,
      pixelRatio: 2,
      filter: (node) => {
        // Exclude minimap, controls, and panel elements from diagram export
        if (
          node.classList?.contains('react-flow__minimap') ||
          node.classList?.contains('react-flow__controls') ||
          node.classList?.contains('react-flow__panel') ||
          node.classList?.contains('diagram-controls-overlay')
        ) {
          return false;
        }
        return true;
      }
    });

    const link = document.createElement('a');
    link.download = fileName;
    link.href = dataUrl;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  } catch (error) {
    console.error('Failed to export canvas as PNG:', error);
    throw error;
  }
}

/**
 * Downloads a single Java source file
 */
export function downloadJavaFile(fileName, code) {
  downloadFile(code, fileName, 'text/x-java-source;charset=utf-8');
}

/**
 * Bundles all generated Java files into a ZIP archive and triggers download
 */
export async function downloadAllJavaFilesAsZip(files, zipFileName = 'JavaSources.zip') {
  if (!files || files.length === 0) {
    throw new Error('No Java files available to download.');
  }

  const zip = new JSZip();
  const folder = zip.folder('src');

  files.forEach((file) => {
    folder.file(file.fileName, file.code);
  });

  // Add a helpful README inside the zip
  folder.file(
    'README.txt',
    `Generated by UML Class Diagram Generator\nTotal Classes: ${files.length}\nDate: ${new Date().toLocaleString()}\n`
  );

  const content = await zip.generateAsync({ type: 'blob' });
  downloadFile(content, zipFileName, 'application/zip');
}
